package ru.javaboys.wootify.bot.strategy;

import ru.javaboys.wootify.entity.StopAction;

/**
 * Торговая стратегия бота. Экземпляр создаётся на каждый запуск бота и используется одним потоком.
 * <p>
 * Контракт устойчивости: всё, что нужно для продолжения работы, стратегия хранит в БД (циклы, ордера,
 * {@link StrategyContext#saveState}). После перезапуска приложения вызывается {@link #start} нового
 * экземпляра, и он обязан продолжить с того же места. Поэтому каждый такт должен быть идемпотентным:
 * сравнивать желаемое с фактическим и досоздавать недостающее, а не полагаться на память.
 * <p>
 * Временные сбои (сеть, биржа, нет цен) стратегия может просто выбрасывать: движок повторит такт.
 */
public interface TradingStrategy {

    /**
     * Запуск или продолжение после перезапуска: восстановить состояние, подготовить биржу.
     */
    void start(StrategyContext ctx);

    /**
     * Один такт работы.
     */
    TickResult tick(StrategyContext ctx);

    /**
     * Остановка по запросу пользователя с указанным действием над ордерами и позицией.
     * Не вызывается при штатном выключении сервера: тогда бот просто продолжит работу после старта.
     */
    void stop(StrategyContext ctx, StopAction action);
}
